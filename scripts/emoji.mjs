// The game's own emoji pictures (Twemoji, CC-BY 4.0) in public/emoji/, one SVG per emoji the code uses.
//   npm run emoji           -> finds every emoji in index.html and src/, downloads any missing picture, writes src/emoji-codes.js
//   node scripts/emoji.mjs --check   (part of npm test) -> fails if any emoji in the code has no picture
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/svg/";
const RE = /[#*0-9]️?⃣|\p{Extended_Pictographic}️?(?:‍\p{Extended_Pictographic}️?)*/gu;
const ALWAYS = /^[\u{1F5D1}⏱⏸]/u;
const isEmoji = s => /\p{Emoji_Presentation}/u.test(String.fromCodePoint(s.codePointAt(0))) || s.includes("️") || s.includes("‍") || s.includes("⃣") || ALWAYS.test(s);
const code = s => { const cps = [...s].map(c => c.codePointAt(0)), zwj = cps.includes(0x200D); return cps.filter(c => zwj || c !== 0xFE0F).map(c => c.toString(16)).join("-"); };

const walk = d => readdirSync(join(root, d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? (e.name === "dev" ? [] : walk(join(d, e.name))) : e.name.endsWith(".js") && e.name !== "emoji-codes.js" ? [join(d, e.name)] : []);
const files = ["index.html", ...walk("src")];
const used = new Map();
for (const f of files) for (const m of readFileSync(join(root, f), "utf8").matchAll(RE)) if (m[0] !== "🪙" && isEmoji(m[0])) used.set(code(m[0]), m[0]);

const dir = join(root, "public", "emoji"); if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
const missing = [...used.keys()].filter(c => !existsSync(join(dir, c + ".svg")));
if (process.argv.includes("--check")) {
  const listed = existsSync(join(root, "src", "emoji-codes.js")) ? readFileSync(join(root, "src", "emoji-codes.js"), "utf8") : "";
  const unlisted = [...used.keys()].filter(c => !listed.includes(`"${c}"`));
  if (missing.length || unlisted.length) { console.log(`✖ emoji without a picture: ${[...missing, ...unlisted].map(c => used.get(c)).join(" ")} (run npm run emoji)`); process.exit(1); }
  console.log(`All ${used.size} emoji have the game's own picture`);
  process.exit(0);
}
for (const c of missing) {
  const res = await fetch(SRC + c + ".svg");
  if (!res.ok) { console.log(`no Twemoji picture for ${used.get(c)} (${c})`); continue; }
  writeFileSync(join(dir, c + ".svg"), await res.text()); console.log("downloaded", used.get(c), c);
}
const have = readdirSync(dir).filter(f => f.endsWith(".svg")).map(f => f.slice(0, -4)).sort();
writeFileSync(join(root, "src", "emoji-codes.js"), `// Generated by scripts/emoji.mjs: the emoji pictures in public/emoji/ (Twemoji, CC-BY 4.0).\nexport default ${JSON.stringify(have)};\n`);
console.log(`${used.size} emoji used, ${have.length} pictures`);
