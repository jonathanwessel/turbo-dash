import { readFileSync, readdirSync } from "node:fs";
import { defineConfig } from "vite";

const { version } = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));

/* Offline support. Generated per release so each version gets its own cache and the exact list of
 * built files to precache. Navigations are network-first (so a new release always loads when online,
 * and the in-game update notice keeps working); hashed assets are cache-first; version.json and
 * sw.js itself always go to the network. */
const swSource = (assets) => `/* Turbo Dash service worker, v${version} (generated by vite.config.js) */
const CACHE = "td-${version}";
const PRECACHE = ${JSON.stringify(["./", "./manifest.webmanifest", "./icon-192.png", "./icon-512.png", "./icon.svg", "./share-qr.svg", ...readdirSync(new URL("./public/emoji", import.meta.url)).map(f => "./emoji/" + f), ...readdirSync(new URL("./public/rooms", import.meta.url)).map(f => "./rooms/" + f), ...readdirSync(new URL("./public/fonts", import.meta.url)).filter(f => f.endsWith(".woff2")).map(f => "./fonts/" + f), ...assets.map(a => "./" + a)])};

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("td-") && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Servers may send "Vary: Origin"; Vite loads its JS/CSS in CORS mode (with an Origin header), so match ignoring Vary.
const MATCH = { ignoreVary: true };
const put = (req, res) => { if (res.ok || res.type === "opaque") { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return res; };

self.addEventListener("fetch", e => {
  const req = e.request; if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.pathname.endsWith("/version.json") || url.pathname.endsWith("/sw.js")) return;
  if (req.mode === "navigate") {
    e.respondWith(fetch(req).then(res => put("./", res)).catch(() => caches.match("./", MATCH)));
    return;
  }
  if (url.origin === location.origin) {
    e.respondWith(caches.match(req, MATCH).then(hit => hit || fetch(req).then(res => put(req, res))));
    return;
  }
  // fonts: serve from cache, refresh in the background
  e.respondWith(caches.match(req, MATCH).then(hit => { const net = fetch(req).then(res => put(req, res)).catch(() => hit); return hit || net; }));
});
`;

export default defineConfig({
  base: "./",
  define: { __APP_VERSION__: JSON.stringify(version) },
  plugins: [{
    // version.json lets a running game notice that a newer release is on the server; sw.js makes it work offline.
    name: "release-files",
    apply: "build",
    generateBundle(_, bundle) {
      this.emitFile({ type: "asset", fileName: "version.json", source: JSON.stringify({ version }) });
      const assets = Object.keys(bundle).filter(f => f.startsWith("assets/"));
      this.emitFile({ type: "asset", fileName: "sw.js", source: swSource(assets) });
    },
  }],
});
